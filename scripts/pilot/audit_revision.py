"""Audit a revised pilot dataset against the committed one (old = ``git show <ref>:datasets/...``).

Reports the old-to-new id mapping and, per episode, exactly which fields changed.  For an episode whose content must stay
the same, only these may differ: ids, stream position, ``corpus_version`` and corpus items APPENDED after the old ones
(the source-comment policy).  Failing tests, diffs, labels, gold evidence, reference repairs, mutants, memory and fault
plans must be identical.  Anything else is reported as UNEXPECTED and the exit status is 1.

    python scripts/pilot/audit_revision.py --new <candidate dir> [--old-ref HEAD] [--write docs/dataset_revision_audit.md]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
IGNORED = {
    "episode_id",
    "stream_position",
    "agent_input.episode_id",
    "agent_input.ci_event.event_id",
    "agent_input.corpus.corpus_id",
    "agent_input.corpus.corpus_version",
    "ground_truth.episode_id",
}
MATERIAL = (
    "agent_input.ci_event.failing_tests",
    "agent_input.ci_event.changed_files",
    "agent_input.ci_event.commit_message",
    "ground_truth.per_test_labels",
    "ground_truth.reference_repairs",
    "ground_truth.injected_mutants",
    "agent_input.visible_memory",
    "fault_plan",
    "scenario",
)


def read_old(ref: str, name: str) -> str:
    done = subprocess.run(
        ["git", "-C", str(ROOT), "show", f"{ref}:datasets/{name}"],
        capture_output=True,
        text=True,
        check=True,
    )
    return done.stdout


def records(text: str) -> list[dict]:
    return [json.loads(line) for line in text.splitlines() if line.strip()]


def diff_paths(old, new, prefix: str = "") -> list[str]:
    if isinstance(old, dict) and isinstance(new, dict):
        out: list[str] = []
        for key in sorted(set(old) | set(new)):
            path = f"{prefix}.{key}" if prefix else key
            if key not in old or key not in new:
                out.append(path)
            else:
                out += diff_paths(old[key], new[key], path)
        return out
    if isinstance(old, list) and isinstance(new, list):
        if len(old) != len(new):
            return [prefix]
        return [
            p
            for i, (a, b) in enumerate(zip(old, new, strict=True))
            for p in diff_paths(a, b, f"{prefix}[{i}]")
        ]
    return [] if old == new else [prefix]


def compare(old: dict, new: dict) -> dict:
    old_items, new_items = (
        old["agent_input"]["corpus"]["items"],
        new["agent_input"]["corpus"]["items"],
    )
    prefix_ok = new_items[: len(old_items)] == old_items
    appended = [i["evidence_id"] for i in new_items[len(old_items) :]] if prefix_ok else None
    o, n = json.loads(json.dumps(old)), json.loads(json.dumps(new))
    for rec in (o, n):
        rec["agent_input"]["corpus"]["items"] = []
    paths = [p for p in diff_paths(o, n) if p not in IGNORED]
    return {"paths": paths, "corpus_prefix_preserved": prefix_ok, "appended": appended}


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--new",
        required=True,
        help="directory with the revised pilot_*.jsonl and pilot_manifest.json",
    )
    parser.add_argument("--old-ref", default="HEAD")
    parser.add_argument("--write", help="write the report to this Markdown file")
    args = parser.parse_args()
    new_dir = Path(args.new)
    old_manifest = json.loads(read_old(args.old_ref, "pilot_manifest.json"))
    new_manifest = json.loads((new_dir / "pilot_manifest.json").read_text())
    lines: list[str] = []
    problems: list[str] = []

    def emit(text: str = "") -> None:
        lines.append(text)

    emit("# Dataset revision audit")
    emit()
    emit(
        f"Old = `git show {args.old_ref}:datasets/...`; new = `{new_dir}`. Generated by `scripts/pilot/audit_revision.py`."
    )
    emit()
    old_by_sha: dict[str, dict] = {}
    new_by_sha: dict[str, dict] = {}
    for split in ("dev", "test"):
        for rec in records(read_old(args.old_ref, f"pilot_{split}.jsonl")):
            old_by_sha[rec["agent_input"]["ci_event"]["commit"]["sha"]] = rec
        for rec in records((new_dir / f"pilot_{split}.jsonl").read_text()):
            new_by_sha[rec["agent_input"]["ci_event"]["commit"]["sha"]] = rec
    keys_old = {
        e["ci_commit"]: (e["key"], e["id"]) for s in old_manifest["splits"].values() for e in s
    }
    keys_new = {
        e["ci_commit"]: (e["key"], e["id"]) for s in new_manifest["splits"].values() for e in s
    }

    emit("## 1. Counts")
    emit()
    for split in ("dev", "test"):
        o = [e["scenario"] for e in old_manifest["splits"][split]]
        n = [e["scenario"] for e in new_manifest["splits"][split]]
        fmt = lambda xs: ", ".join(f"{k} x{xs.count(k)}" for k in sorted(set(xs)))
        emit(f"- **{split}**: {len(o)} -> {len(n)} ({fmt(o)}  ->  {fmt(n)})")
    emit(
        f"- **total**: {len(old_by_sha)} -> {len(new_by_sha)} (the 5-day plan targets 6-12; 13 is documented as exceeding it)"
    )
    emit()
    emit("## 2. Old-to-new id mapping")
    emit()
    emit("| CI commit | manifest key (old -> new) | old id | new id | scenario old -> new |")
    emit("|---|---|---|---|---|")
    for sha in sorted(
        set(old_by_sha) | set(new_by_sha), key=lambda s: (keys_new.get(s) or ("", "zz"))[1]
    ):
        ko, kn = keys_old.get(sha), keys_new.get(sha)
        so = old_by_sha[sha]["scenario"] if sha in old_by_sha else "-"
        sn = new_by_sha[sha]["scenario"] if sha in new_by_sha else "-"
        emit(
            f"| `{sha[:8]}` | {ko[0] if ko else '-'} -> {kn[0] if kn else '-'} | {ko[1] if ko else 'new'} | {kn[1] if kn else 'removed'} | {so} -> {sn} |"
        )
    emit()
    emit("## 3. Per-episode changes")
    emit()
    emit(
        "| new id | verdict | changed fields (besides ids / stream position / corpus_version) | appended corpus items |"
    )
    emit("|---|---|---|---|")
    for sha, new in sorted(new_by_sha.items(), key=lambda kv: keys_new[kv[0]][1]):
        nid = keys_new[sha][1]
        if sha not in old_by_sha:
            emit(
                f"| {nid} | NEW episode | all | {len(new['agent_input']['corpus']['items'])} (full corpus) |"
            )
            continue
        old = old_by_sha[sha]
        c = compare(old, new)
        reclass = old["scenario"] != new["scenario"]
        gold_only = bool(c["paths"]) and all(
            "gold_evidence_ids" in p or p == "ground_truth.note" for p in c["paths"]
        )
        if reclass:
            oi = {i["evidence_id"]: i for i in old["agent_input"]["corpus"]["items"]}
            ni = {i["evidence_id"]: i for i in new["agent_input"]["corpus"]["items"]}
            c["appended"] = (
                [f"+{k}" for k in sorted(set(ni) - set(oi))]
                + [f"~{k} (text changed)" for k in sorted(set(oi) & set(ni)) if oi[k] != ni[k]]
                + [f"-{k}" for k in sorted(set(oi) - set(ni))]
            )
            c["corpus_prefix_preserved"] = True
        if not c["corpus_prefix_preserved"]:
            verdict = "UNEXPECTED (existing corpus items changed)"
            problems.append(f"{nid}: existing corpus items changed")
        elif reclass:
            verdict = f"RECLASSIFIED {old['scenario']} -> {new['scenario']} (approved)"
        elif not c["paths"]:
            verdict = "content unchanged"
        elif gold_only:
            verdict = "gold evidence changed (approved)"
        else:
            verdict = "UNEXPECTED"
            problems.append(f"{nid}: unexpected changes {c['paths'][:5]}")
        shown = ", ".join(f"`{p}`" for p in c["paths"][:6]) + (
            " ..." if len(c["paths"]) > 6 else ""
        )
        emit(f"| {nid} | {verdict} | {shown or '-'} | {', '.join(c['appended'] or []) or 'none'} |")
    emit()
    emit("## 4. Invariants for episodes that must not change")
    emit()
    emit(
        "| episode | failing tests | agent-visible diffs | labels | reference repairs | mutants | memory | fault plan |"
    )
    emit("|---|:-:|:-:|:-:|:-:|:-:|:-:|:-:|")
    watch = {
        "failing tests": "agent_input.ci_event.failing_tests",
        "diffs": "agent_input.ci_event.changed_files",
        "labels": "ground_truth.per_test_labels",
        "refs": "ground_truth.reference_repairs",
        "mutants": "ground_truth.injected_mutants",
        "memory": "agent_input.visible_memory",
        "faults": "fault_plan",
    }
    for sha, new in sorted(new_by_sha.items(), key=lambda kv: keys_new[kv[0]][1]):
        if sha not in old_by_sha or old_by_sha[sha]["scenario"] != new["scenario"]:
            continue
        c = compare(old_by_sha[sha], new)
        cells = []
        for w in watch.values():
            hit = [p for p in c["paths"] if p.startswith(w)]
            cells.append(
                "same"
                if not hit
                else "gold ids only"
                if all("gold_evidence_ids" in p for p in hit)
                else "DIFFERS"
            )
        emit(f"| {keys_new[sha][1]} | " + " | ".join(cells) + " |")
    emit()
    emit("## 5. Result")
    emit()
    emit(
        "UNEXPECTED differences: **none**"
        if not problems
        else "UNEXPECTED differences:\n" + "\n".join(f"- {p}" for p in problems)
    )
    text = "\n".join(lines) + "\n"
    sys.stdout.write(text)
    if args.write:
        Path(args.write).write_text(text, encoding="utf-8")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
